import React from 'react';
import { CheckCircle2, Circle, Clock, ArrowRight, Flame, CheckSquare, Plus } from 'lucide-react';
import { SalesTask, InquiryLead } from '../types.ts';

interface TasksTabProps {
  tasks: SalesTask[];
  leads: InquiryLead[];
  onToggleTask: (taskId: string) => void;
  onSelectLead: (lead: InquiryLead) => void;
}

export const TasksTab: React.FC<TasksTabProps> = ({
  tasks,
  leads,
  onToggleTask,
  onSelectLead,
}) => {
  const pendingTasks = tasks.filter((t) => t.status === 'pending');
  const completedTasks = tasks.filter((t) => t.status === 'completed');

  const handleOpenLeadForTask = (leadId: string) => {
    const matchedLead = leads.find((l) => l.id === leadId);
    if (matchedLead) {
      onSelectLead(matchedLead);
    }
  };

  return (
    <div className="space-y-6 text-slate-900 dark:text-slate-100 transition-colors duration-200">
      {/* Header */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 pb-4 border-b border-slate-200 dark:border-neutral-800">
        <div>
          <h2 className="text-xl sm:text-2xl font-extrabold tracking-tight text-black dark:text-white">
            Sales Action Tasks
          </h2>
          <p className="text-xs sm:text-sm text-slate-600 dark:text-neutral-400 mt-0.5">
            Actionable follow-ups and quotation approvals generated by Alpha.
          </p>
        </div>

        <div className="inline-flex items-center gap-2 text-xs font-semibold px-3 py-1.5 rounded-xl bg-slate-100 dark:bg-neutral-900 border border-slate-200 dark:border-neutral-800">
          <CheckSquare className="w-3.5 h-3.5 text-slate-500" />
          <span>{pendingTasks.length} Pending Tasks</span>
        </div>
      </div>

      {/* Pending Tasks Container */}
      <div className="p-5 sm:p-6 rounded-2xl bg-white dark:bg-black border border-slate-200 dark:border-neutral-800 shadow-2xs space-y-4">
        <div className="flex items-center justify-between pb-3 border-b border-slate-100 dark:border-neutral-800">
          <div className="flex items-center space-x-2">
            <h3 className="text-sm font-bold text-black dark:text-white">Pending Action Items</h3>
            <span className="px-2 py-0.5 text-[10px] font-bold rounded-full bg-slate-100 dark:bg-neutral-800 text-slate-800 dark:text-neutral-200 border border-slate-200 dark:border-neutral-700">
              {pendingTasks.length}
            </span>
          </div>
        </div>

        {pendingTasks.length === 0 ? (
          <div className="py-12 text-center text-slate-500 dark:text-neutral-400">
            <div className="w-10 h-10 rounded-2xl bg-slate-100 dark:bg-neutral-900 flex items-center justify-center mx-auto mb-2 text-emerald-500">
              <CheckCircle2 className="w-5 h-5" />
            </div>
            <p className="text-sm font-bold text-black dark:text-white">All clear! No pending tasks.</p>
            <p className="text-xs text-slate-500 dark:text-neutral-400 mt-0.5">New tasks will be automatically generated as new inquiries arrive.</p>
          </div>
        ) : (
          <div className="space-y-2.5">
            {pendingTasks.map((task) => (
              <div
                key={task.id}
                className="p-4 rounded-xl bg-slate-50 dark:bg-neutral-900/60 border border-slate-200/90 dark:border-neutral-800 flex items-center justify-between gap-3 hover:bg-slate-100/80 dark:hover:bg-neutral-900 transition-colors"
              >
                <div className="flex items-start space-x-3.5 min-w-0">
                  <button
                    onClick={() => onToggleTask(task.id)}
                    className="mt-0.5 text-slate-400 hover:text-emerald-600 transition-colors cursor-pointer flex-shrink-0"
                    title="Mark task as complete"
                  >
                    <Circle className="w-4 h-4" />
                  </button>

                  <div className="min-w-0">
                    <div className="flex items-center space-x-2 flex-wrap gap-y-1">
                      <span className="text-xs font-bold text-black dark:text-white">{task.companyName}</span>
                      {task.leadScore === 'HOT' && (
                        <span className="text-[10px] font-bold px-2 py-0.2 rounded-full bg-rose-50 text-rose-700 dark:bg-rose-950/60 dark:text-rose-300 border border-rose-200 dark:border-rose-800">
                          🔥 HOT
                        </span>
                      )}
                      <span
                        className={`text-[10px] font-bold px-2 py-0.2 rounded-full border ${
                          task.priority === 'high'
                            ? 'bg-rose-50 text-rose-700 dark:bg-rose-950/60 dark:text-rose-300 border-rose-200 dark:border-rose-800'
                            : 'bg-amber-50 text-amber-800 dark:bg-amber-950/60 dark:text-amber-300 border-amber-200 dark:border-amber-800'
                        }`}
                      >
                        {task.priority.toUpperCase()} PRIORITY
                      </span>
                    </div>

                    <p className="text-xs text-slate-800 dark:text-neutral-200 font-medium mt-1">{task.title}</p>
                    <p className="text-[11px] text-slate-500 dark:text-neutral-400 font-mono mt-0.5">Due: {task.dueDate}</p>
                  </div>
                </div>

                <div className="flex items-center space-x-2 flex-shrink-0">
                  <button
                    onClick={() => handleOpenLeadForTask(task.leadId)}
                    className="inline-flex items-center gap-1 text-xs px-3.5 py-2 rounded-xl bg-black text-white dark:bg-white dark:text-black hover:bg-neutral-800 dark:hover:bg-neutral-100 font-bold transition-all cursor-pointer shadow-2xs active:scale-[0.98] interactive-button"
                  >
                    <span>Execute</span>
                    <ArrowRight className="w-3 h-3" />
                  </button>
                </div>
              </div>
            ))}
          </div>
        )}
      </div>

      {/* Completed Tasks */}
      {completedTasks.length > 0 && (
        <div className="p-5 sm:p-6 rounded-2xl bg-white dark:bg-black border border-slate-200 dark:border-neutral-800 shadow-2xs space-y-4">
          <div className="flex items-center justify-between pb-3 border-b border-slate-100 dark:border-neutral-800">
            <h3 className="text-xs font-bold uppercase tracking-wider text-slate-500 dark:text-neutral-400">Completed Tasks ({completedTasks.length})</h3>
          </div>

          <div className="space-y-2">
            {completedTasks.map((task) => (
              <div
                key={task.id}
                className="p-3.5 rounded-xl bg-slate-50/60 dark:bg-neutral-900/30 border border-slate-200/60 dark:border-neutral-800 flex items-center justify-between opacity-80"
              >
                <div className="flex items-center space-x-3">
                  <button
                    onClick={() => onToggleTask(task.id)}
                    className="text-emerald-600 hover:text-slate-400 transition-colors cursor-pointer"
                  >
                    <CheckCircle2 className="w-4 h-4" />
                  </button>
                  <div>
                    <span className="text-xs font-semibold line-through text-slate-500 dark:text-neutral-400">
                      {task.companyName}: {task.title}
                    </span>
                  </div>
                </div>
                <span className="text-[10px] text-emerald-700 dark:text-emerald-400 font-mono font-bold">Completed</span>
              </div>
            ))}
          </div>
        </div>
      )}
    </div>
  );
};
